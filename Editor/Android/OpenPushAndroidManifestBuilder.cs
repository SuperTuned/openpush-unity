using System.Security;
using System.Text;
using OpenPushSDK.Core;

namespace OpenPushSDK.Editor
{
    internal sealed class OpenPushAndroidManifestInput
    {
        public string AppId, SdkKey, FirebaseProjectId, FirebaseApplicationId, FirebaseApiKey;
        public OpenPushAndroidPushDelivery Delivery;
        public bool SuppressLaunchUrls;
        /// <summary>The reused status-bar icon's drawable name, or null for OpenPush's defaults.</summary>
        public string NotificationIcon;
    }

    /// <summary>
    /// The adapter library's manifest. Automatic: app id, SDK key, the launch-URL opt-out when the
    /// settings turn launch URLs off, and (when google-services.json is not used) the three Firebase
    /// values the native FCM module reads. Forward (also named HostOwned): the native messaging service is
    /// removed so the host's FirebaseMessagingService is the only one, and ai.openpush.fcm.delivery is
    /// "forward", which makes the native FCM module disable that service at startup should it ever be
    /// merged in again (a guard against pushes split between two services).
    /// </summary>
    internal static class OpenPushAndroidManifestBuilder
    {
        internal static string Build(OpenPushAndroidManifestInput input)
        {
            var sb = new StringBuilder();
            sb.Append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
            sb.Append("<!-- Generated by OpenPush from OpenPushSettings at export. Edit the settings asset instead. -->\n");
            sb.Append("<manifest xmlns:android=\"http://schemas.android.com/apk/res/android\"\n");
            sb.Append("          xmlns:tools=\"http://schemas.android.com/tools\"\n");
            sb.Append("          package=\"ai.openpush.unity\">\n");
            sb.Append("    <uses-permission android:name=\"android.permission.POST_NOTIFICATIONS\" />\n");
            sb.Append("    <application>\n");
            Meta(sb, "ai.openpush.app_id", input.AppId);
            Meta(sb, "ai.openpush.sdk_key", input.SdkKey);
            // Read by the native tap trampoline: open the app, not the push's launch URL.
            if (input.SuppressLaunchUrls) Meta(sb, "ai.openpush.suppress_launch_urls", "true");
            if (input.Delivery == OpenPushAndroidPushDelivery.Automatic)
            {
                Meta(sb, "ai.openpush.fcm.project_id", input.FirebaseProjectId);
                Meta(sb, "ai.openpush.fcm.application_id", input.FirebaseApplicationId);
                Meta(sb, "ai.openpush.fcm.api_key", input.FirebaseApiKey);
                // A resource reference: the native renderer reads it with getInt.
                if (IsResourceName(input.NotificationIcon))
                    sb.Append("        <meta-data android:name=\"ai.openpush.notification_icon\" android:resource=\"@drawable/")
                      .Append(input.NotificationIcon.Trim()).Append("\" />\n");
            }
            else
            {
                Meta(sb, "ai.openpush.fcm.delivery", "forward");
                sb.Append("        <service android:name=\"ai.openpush.android.fcm.OpenPushMessagingService\" tools:node=\"remove\" />\n");
            }
            sb.Append("    </application>\n");
            sb.Append("</manifest>\n");
            return sb.ToString();
        }

        /// <summary>An Android resource name (lowercase letters, digits, underscores); anything else is never written.</summary>
        internal static bool IsResourceName(string value)
            => !string.IsNullOrWhiteSpace(value) && System.Text.RegularExpressions.Regex.IsMatch(value.Trim(), "^[a-z][a-z0-9_]*$");

        private static void Meta(StringBuilder sb, string name, string value)
        {
            if (string.IsNullOrWhiteSpace(value)) return;
            sb.Append("        <meta-data android:name=\"").Append(name).Append("\" android:value=\"")
              .Append(SecurityElement.Escape(value.Trim())).Append("\" />\n");
        }
    }
}
