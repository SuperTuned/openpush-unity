using System.IO;
using OpenPushSDK.Core;
using UnityEditor;
using UnityEngine;

namespace OpenPushSDK.Editor
{
    /// <summary>Keeps the host's generated OpenPushDependencies.xml in step with the delivery mode.</summary>
    [InitializeOnLoad]
    public static class OpenPushAndroidDependencies
    {
        public const string OutputPath = "Assets/Plugins/OpenPush/Editor/OpenPushDependencies.xml";
        private const string Header = "<!-- Generated by OpenPush from OpenPushSettings.AndroidPushDelivery. Do not edit. -->\n";

        static OpenPushAndroidDependencies() => EditorApplication.delayCall += () => WriteNow();

        /// <summary>Writes the file when its content differs. True when it changed (a resolve is due).</summary>
        public static bool WriteNow()
        {
            var settings = OpenPushSetupAssets.Loadable();
            var delivery = settings != null ? settings.AndroidPushDelivery : OpenPushAndroidPushDelivery.Automatic;
            var content = Header + OpenPushAndroidDependenciesXml.Build(delivery);
            if (File.Exists(OutputPath) && File.ReadAllText(OutputPath) == content) return false;
            Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
            File.WriteAllText(OutputPath, content);
            AssetDatabase.ImportAsset(OutputPath);
            Debug.Log("OpenPush: wrote " + OutputPath + " (" + delivery + ")");
            return true;
        }
    }
}
